using System;
using System.Buffers.Binary;
using System.Collections.Generic;
using System.Globalization;
using System.IO;
using System.Linq;
using Avalonia;
using Avalonia.Media.Imaging;
using Avalonia.Platform;
using Enigma.Launchpad.Desktop.UnitTests.Infrastructure;
using Xunit;

namespace Enigma.Launchpad.Desktop.UnitTests;

/// <summary>
/// The application icon as the assembly ships it: the ten frames of <c>app.ico</c>, the copy of its largest frame,
/// the copy written to the output directory, and the copies the Linux installer installs.
/// </summary>
/// <remarks>
/// The SVG master, the frames and the icon are generated by the Branding repository's <c>Apps/export.py</c> and
/// copied here by hand, so these pin what a regeneration has to keep: the sizes, the encoding, and the copies being
/// copies.
/// </remarks>
[Collection(HeadlessCollection.Name)]
public sealed class AppIconTests(HeadlessAvaloniaFixture fixture)
{
    private static ReadOnlySpan<byte> PngSignature => [0x89, 0x50, 0x4E, 0x47, 0x0D, 0x0A, 0x1A, 0x0A];

    [Fact]
    public void TheIcon_HoldsTenSquare32BitPngFramesFrom16To256()
        => fixture.Run(() =>
        {
            IReadOnlyList<IconFrame> frames = ReadFrames(ReadAsset("app.ico"));

            Assert.Equal([16, 20, 24, 32, 40, 48, 64, 96, 128, 256], frames.Select(frame => frame.Size));

            foreach (IconFrame frame in frames)
            {
                Assert.Equal(32, frame.BitCount);
                Assert.True(frame.Png.AsSpan().StartsWith(PngSignature), $"the {frame.Size} frame is not a PNG");

                // The PNG's own header says the same size the directory does, and RGBA at 8 bits.
                Assert.Equal(frame.Size, BinaryPrimitives.ReadInt32BigEndian(frame.Png.AsSpan(16, 4)));
                Assert.Equal(frame.Size, BinaryPrimitives.ReadInt32BigEndian(frame.Png.AsSpan(20, 4)));
                Assert.Equal(8, frame.Png[24]);
                Assert.Equal(6, frame.Png[25]);
            }
        });

    [Fact]
    public void TheLargeImage_IsTheIconsLargestFrameByteForByte()
        => fixture.Run(() =>
        {
            byte[] image = ReadAsset("app-256.png");
            IconFrame largest = ReadFrames(ReadAsset("app.ico"))[^1];

            Assert.Equal(largest.Png, image);

            using MemoryStream stream = new(image);
            using Bitmap bitmap = new(stream);
            Assert.Equal(new PixelSize(256, 256), bitmap.PixelSize);
        });

    [Fact]
    public void TheLinuxIcons_AreTheIconsFramesByteForByteInEverySizeTheInstallerInstalls()
        => fixture.Run(() =>
        {
            int[] sizes = IconSizes("install.sh");
            IReadOnlyList<IconFrame> frames = ReadFrames(ReadAsset("app.ico"));

            // The uninstaller removes what the installer wrote, so it has to know the same sizes.
            Assert.Equal(sizes, IconSizes("uninstall.sh"));
            Assert.Equal([16, 24, 32, 48, 64, 96, 128, 256], sizes);

            foreach (int size in sizes)
            {
                IconFrame frame = Assert.Single(frames, candidate => candidate.Size == size);
                byte[] png = File.ReadAllBytes(Path.Combine(RepositoryRoot.Find(), "packaging", "linux", "icons", $"enigma-launchpad-{size}.png"));

                Assert.Equal(frame.Png, png);
            }
        });

    [Fact]
    public void TheIconFile_SitsInTheOutputDirectoryByteForByte()
        => fixture.Run(() =>
        {
            // The application's copy of its output reaches this test's output as a referenced project's file, under
            // the same name (FEATURE-7F4A).
            string copy = Path.Combine(AppContext.BaseDirectory, "app.ico");

            Assert.True(File.Exists(copy), $"no app.ico in {AppContext.BaseDirectory}");
            Assert.Equal(ReadAsset("app.ico"), File.ReadAllBytes(copy));
        });

    private static byte[] ReadAsset(string name)
    {
        using Stream asset = AssetLoader.Open(new Uri($"avares://Enigma.Launchpad.Desktop/Assets/{name}"));
        using MemoryStream copy = new();
        asset.CopyTo(copy);
        return copy.ToArray();
    }

    /// <summary>
    /// Reads an .ico's directory: a six-byte header (reserved, type 1, count), then sixteen bytes per frame, in which
    /// a width or height of 0 means 256.
    /// </summary>
    private static List<IconFrame> ReadFrames(byte[] icon)
    {
        ReadOnlySpan<byte> data = icon;
        Assert.Equal(0, BinaryPrimitives.ReadUInt16LittleEndian(data[0..]));
        Assert.Equal(1, BinaryPrimitives.ReadUInt16LittleEndian(data[2..]));

        int count = BinaryPrimitives.ReadUInt16LittleEndian(data[4..]);
        List<IconFrame> frames = new(count);

        for (int index = 0; index < count; index++)
        {
            ReadOnlySpan<byte> entry = data.Slice(6 + (16 * index), 16);
            int width = entry[0] == 0 ? 256 : entry[0];
            int height = entry[1] == 0 ? 256 : entry[1];
            Assert.Equal(width, height);

            int length = BinaryPrimitives.ReadInt32LittleEndian(entry[8..]);
            int offset = BinaryPrimitives.ReadInt32LittleEndian(entry[12..]);
            Assert.InRange(offset + length, 0, icon.Length);

            frames.Add(new IconFrame(width, BinaryPrimitives.ReadUInt16LittleEndian(entry[6..]), icon[offset..(offset + length)]));
        }

        return frames;
    }

    /// <summary>
    /// The sizes a Linux packaging script's <c>ICON_SIZES</c> array lists, in its order.
    /// </summary>
    private static int[] IconSizes(string script)
    {
        const string declaration = "readonly ICON_SIZES=(";

        string line = Assert.Single(
            File.ReadAllLines(Path.Combine(RepositoryRoot.Find(), "packaging", "linux", script)),
            text => text.StartsWith(declaration, StringComparison.Ordinal));

        return [.. line[declaration.Length..line.IndexOf(')', StringComparison.Ordinal)]
            .Split(' ', StringSplitOptions.RemoveEmptyEntries)
            .Select(size => int.Parse(size, CultureInfo.InvariantCulture))];
    }

    private sealed record IconFrame(int Size, int BitCount, byte[] Png);
}
